// Catalog Query API for fast client-side performance
const SHINE_CATALOG = {
    getAll: () => SHINE_PRODUCTS,
    getCategories: () => SHINE_CATEGORIES,
    getById: (id) => SHINE_PRODUCTS.find(p => p.id === id),
    getByCategory: (catId) => SHINE_PRODUCTS.filter(p => p.category.toLowerCase() === (catId || '').toLowerCase()),
    getFeatured: () => SHINE_PRODUCTS.filter(p => p.featured),
    getDeals: () => SHINE_PRODUCTS.filter(p => p.dealOfDay),
    getTrending: () => SHINE_PRODUCTS.filter(p => p.trending),
    formatINR: (amount) => {
        if (typeof amount !== 'number') return '₹0';
        return '₹' + amount.toLocaleString('en-IN');
    },
    search: (query, category = 'all') => {
        const q = (query || '').toLowerCase().trim();
        return SHINE_PRODUCTS.filter(p => {
            const matchesCat = (category === 'all' || !category) ? true : p.category.toLowerCase() === category.toLowerCase();
            const matchesText = !q || 
                p.name.toLowerCase().includes(q) ||
                p.brand.toLowerCase().includes(q) ||
                p.categoryName.toLowerCase().includes(q) ||
                (p.specs && p.specs.some(s => s.toLowerCase().includes(q)));
            return matchesCat && matchesText;
        });
    }
};

// Robust, XML-escaped SVG Fallback image generator for offline or CDN loading issues
function getProductFallbackImage(name, categoryName) {
    const rawName = (name || 'Tech Product').slice(0, 24);
    const safeName = rawName
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
    const safeCat = (categoryName || 'SHINE TECH').toUpperCase()
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;');

    const svg = '<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600" viewBox="0 0 600 600">' +
        '<rect width="100%" height="100%" fill="#080D19"/>' +
        '<rect x="24" y="24" width="552" height="552" rx="20" fill="#0D1527" stroke="#087BFF" stroke-width="2" stroke-opacity="0.3"/>' +
        '<circle cx="300" cy="240" r="85" fill="#087BFF" fill-opacity="0.12" stroke="#00C8F8" stroke-width="2"/>' +
        '<polygon points="300,180 345,240 300,300 255,240" fill="none" stroke="#00C8F8" stroke-width="4"/>' +
        '<circle cx="300" cy="240" r="14" fill="#FFFFFF"/>' +
        '<text x="300" y="370" font-family="-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,sans-serif" font-size="16" font-weight="700" fill="#00C8F8" text-anchor="middle" letter-spacing="3">' + safeCat + '</text>' +
        '<text x="300" y="415" font-family="-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,sans-serif" font-size="20" font-weight="600" fill="#FFFFFF" text-anchor="middle">' + safeName + '</text>' +
        '<text x="300" y="455" font-family="-apple-system,BlinkMacSystemFont,Segoe UI,Roboto,sans-serif" font-size="13" font-weight="500" fill="#717478" text-anchor="middle">SHINE ASSURED • 100% GENUINE</text>' +
        '</svg>';

    return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

// Global safe image error handler to prevent broken-image icons and infinite error loops
function handleImageError(imgEl, productIdOrName, categoryName) {
    if (!imgEl) return;
    imgEl.onerror = null; // Prevent recursion
    if (productIdOrName && typeof SHINE_CATALOG !== 'undefined') {
        const prod = SHINE_CATALOG.getById(productIdOrName);
        if (prod) {
            imgEl.src = getProductFallbackImage(prod.name, prod.categoryName);
            return;
        }
    }
    imgEl.src = getProductFallbackImage(productIdOrName || 'Product', categoryName || 'SHINE TECH');
}

